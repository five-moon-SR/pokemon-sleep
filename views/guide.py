st.header("4. 強ポケ捕獲方針の見方")
st.markdown(
    """
種族の「強さ」を、攻略サイト4ソースの**人間による評価**を統合したティアで並べています。
計算だけで出したティアは食材収集性能に寄るため、スキルで強い種が沈みます。
そこを避けるため、人が評価しているソースだけを採用しています。

- **SS / S / A …**：統合ティア。全ソースが最上位に置いたのはサーナイトとカイリューだけ
- **3サイト一致**：複数サイトが同じ評価＝ほぼ確定
- **評価が割れている**：サイトによって評価軸が違う（食材で見るかスキルで見るか）
- **参考値**：1ソースしか評価していない。新実装・伝説・ニッチな種に多い
- **📊 評価の内訳**：どのサイトが何点を付けたかを確認できる

出現マップも表示されます。**専属**＝そのマップでしか捕れない種で、
複数マップに出る種より優先度が高くなります（223種中175種が専属）。
「🗺 おすすめマップ」は、狙っている種が何体出るかをマップ別に集計したものです。
"""
)

st.header("5. アイテム投資先の決め方")
st.markdown(
    """
「評価値がいくつ伸びるか」ではなく、**登録済みの定番プランの週エナジーが
実際にいくら伸びるか**で並べています。

- アイテム後の個体を、各プランの5枠すべてに差し込んで最良を採ります。
  だから**ベンチの個体でも、差し込んで伸びるなら上位に来ます**（🆕 定番入り）
- 基準は「アイテムを使わずに差し込んだ最良」。素のままで足りている個体に
  アイテムの手柄を付けないので、ここに出る値は**アイテムの限界貢献**です
- **今週のプラン**は他より重く見ます（今週設定が無ければ全プラン同じ重み）
- サブスキルのたねは抽選なので、分岐の**期待値**（確率で均した値）です
- 実戦で動かない個体は「実戦の改善なし」と表示し、育成後評価の伸びで並べます

**定番プランを埋めるほど精度が上がります**（フィールド × 料理カテゴリで最大24枠）。
1件も無いと実改善が測れないので、評価値順のフォールバックになります。

編成ページの「🗂 定番プランの充足」から**全枠をまとめて自動生成**できます（20秒前後）。
既存プランがあるときは上書きするか聞かれ、上書きした枠は
「何が何に変わって、週エナジーがいくら動いたか」が枠ごとに出ます。
"""
)

st.header("6. 強い料理を狙う（逆引き）")
st.markdown(
    """
編成ページの「🍳 強い料理を狙う」タブは、料理の側からたどります。

- 選んでいるカテゴリの料理を**エナジーの高い順**に並べ、それぞれ
  「今の手札で作れるか」「作れないなら何の食材が何個/日足りないか」を出します
- 不足食材ごとに、それを供給できる**未所持の最終進化種**を、
  種族ティアと出現マップつきで挙げます
- 「最短で狙うなら」は、穴ごとに最有力の1体を拾った最小の必要種リストです

育成・捕獲タブの捕獲候補とは役割が違います。あちらは**今の主料理を1品固定**して
「1体入れるといくら伸びるか」を測るため、必要食材を2つ以上欠いた料理では
差分がゼロに潰れて候補が出ません。**まだ作れない強い料理**はこちらで見てください。
"""
)

st.header("7. 計算上の注意")
st.markdown(
    """
- 標準評価は**月曜開始時の食材在庫ゼロ**。実運用は「今週の持越し食材」で比較できます
- 料理チャンスの蓄積と大成功時リセットは期待値で近似しています
- げんきオールは発動期待回数からチーム全体の稼働増分を計算します
- げんきエール・自己回復は精密シミュレーション対象外で、既存の近似評価を使います
- 最大所持数による夜間の取りこぼしや、手動交代運用は未反映です
- 新ポケモン・新料理・仕様変更時はマスターデータの更新が必要です
- **料理エナジーは登録した料理レベルで計算します**。編成ページの主料理の下で
  1品ずつ登録でき、未登録はLv1（未開拓）として扱います。倍率は全料理共通で、
  Lv1=×1.00／Lv30=×1.61／Lv60=×3.03／上限Lv70=×3.58。
  レベルを登録していない強い料理を過大評価しないための仕組みです
- ごちゃまぜ系3種はレシピレベルの恩恵を受けないため、常に基準エナジーのままです
- 鍋容量を超える料理は主料理の候補から外れます。ただし料理パワーアップS持ちが
  編成にいる場合は「素の容量＋1日ぶんの積み上げ」まで候補に残します
"""
)

